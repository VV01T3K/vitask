#!/usr/bin/env node
// Prints the SQL that creates Better Auth's tables for this Worker's auth options (user, session, account,
// verification, passkey, rateLimit), compiled by Better Auth itself against an empty SQLite database. Use it to write
// the next migration when the auth options change:  node scripts/auth-schema.mjs > migrations/NNNN_name.sql
// (for a change, diff against the previous output and keep only the delta).
import { DatabaseSync } from "node:sqlite";

import { getMigrations } from "better-auth/db/migration";

import { authOptions } from "../src/auth.ts";

const options = authOptions(
  {
    appUrl: "http://localhost",
    secret: "schema-only-secret-0123456789abcdef",
    cookieSecret: "schema-only",
    extraOrigins: [],
  },
  new DatabaseSync(":memory:"),
);
const { compileMigrations } = await getMigrations(options);
const sql = await compileMigrations();
process.stdout.write(
  `-- Better Auth schema, generated by scripts/auth-schema.mjs.\n${sql.trim()}\n`,
);
